function esRisk(id: string, field: 0 | 1, fallback: string): string {
  const key = Object.keys(ES_RISK_TEXT).find((k) => id === k || id.startsWith(`${k}-`))
  const text = key ? ES_RISK_TEXT[key][field] : ''
  return text || fallback
}

